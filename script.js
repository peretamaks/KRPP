    // Функція відкриття модального вікна з порядком виконання
    function showLabDetails(labId) {
      const data = labInstructions[labId];
      if (!data) return;

      document.getElementById('labModalLabel').innerText = data.title;
      let html = '<ol class="ps-3 mb-0">';
      data.steps.forEach(step => {
        html += `<li class="mb-2 text-dark">${step}</li>`;
      });
      html += '</ol>';
      document.getElementById('labModalContent').innerHTML = html;

      const modal = new bootstrap.Modal(document.getElementById('labDetailsModal'));
      modal.show();
    }

    // Допоміжна функція перемикання розділів із посилань/кнопок
    function activateTab(tabName) {
      const tabButton = document.getElementById(`tab-${tabName}-btn`);
      if (tabButton) {
        const trigger = new bootstrap.Tab(tabButton);
        trigger.show();
        window.scrollTo({ top: 0, behavior: 'smooth' });
      }
    }